-- Immutable driver dispatch and settlement migration. Run as the schema owner.
CREATE TABLE public.driver_profile (
    driver_id bigint PRIMARY KEY REFERENCES public.customers(id) ON DELETE RESTRICT,
    branch_id integer NOT NULL REFERENCES public.branch(branch_id),
    hourly_rate numeric(10,2) NOT NULL DEFAULT 0 CHECK (hourly_rate >= 0),
    per_delivery_rate numeric(10,2) NOT NULL DEFAULT 0 CHECK (per_delivery_rate >= 0),
    active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX driver_profile_branch_idx ON public.driver_profile(branch_id);

CREATE TABLE public.driver_shift (
    shift_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    driver_id bigint NOT NULL REFERENCES public.driver_profile(driver_id),
    branch_id integer NOT NULL REFERENCES public.branch(branch_id),
    business_date date NOT NULL,
    clocked_in_at timestamptz NOT NULL DEFAULT now(),
    clocked_out_at timestamptz,
    approved_minutes integer CHECK (approved_minutes >= 0),
    hourly_rate numeric(10,2) NOT NULL CHECK (hourly_rate >= 0),
    per_delivery_rate numeric(10,2) NOT NULL CHECK (per_delivery_rate >= 0),
    returning_at timestamptz,
    state text NOT NULL DEFAULT 'ACTIVE' CHECK (state IN ('ACTIVE', 'CLOCKED_OUT', 'SETTLED'))
);
CREATE UNIQUE INDEX driver_one_open_shift ON public.driver_shift(driver_id) WHERE state <> 'SETTLED';
CREATE INDEX driver_shift_branch_date_idx ON public.driver_shift(branch_id, business_date DESC);

CREATE TABLE public.delivery_assignment (
    assignment_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL UNIQUE REFERENCES public.customer_order(order_id) ON DELETE RESTRICT,
    driver_id bigint NOT NULL REFERENCES public.driver_profile(driver_id),
    shift_id bigint NOT NULL REFERENCES public.driver_shift(shift_id),
    branch_id integer NOT NULL REFERENCES public.branch(branch_id),
    assigned_by bigint REFERENCES public.customers(id),
    self_claimed boolean NOT NULL DEFAULT false,
    state text NOT NULL DEFAULT 'ASSIGNED' CHECK (state IN ('ASSIGNED', 'PICKED_UP', 'DELIVERED', 'CANCELLED')),
    assigned_at timestamptz NOT NULL DEFAULT now(),
    picked_up_at timestamptz,
    delivered_at timestamptz
);
CREATE INDEX delivery_assignment_driver_idx ON public.delivery_assignment(driver_id, state, assigned_at);
CREATE INDEX delivery_assignment_branch_idx ON public.delivery_assignment(branch_id, state, assigned_at);

CREATE TABLE public.driver_dispatch_event (
    event_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shift_id bigint NOT NULL REFERENCES public.driver_shift(shift_id),
    assignment_id bigint REFERENCES public.delivery_assignment(assignment_id),
    actor_id bigint REFERENCES public.customers(id),
    actor_username varchar(255) NOT NULL,
    branch_id integer NOT NULL REFERENCES public.branch(branch_id),
    event_type varchar(40) NOT NULL,
    occurred_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX driver_dispatch_event_shift_idx ON public.driver_dispatch_event(shift_id, occurred_at);

-- Reserved for provider-verified payments. No browser or driver write grant exists.
-- An absent row means a cash order with zero online payment and zero tips.
CREATE TABLE public.delivery_payment (
    order_id bigint PRIMARY KEY REFERENCES public.customer_order(order_id) ON DELETE RESTRICT,
    method text NOT NULL CHECK (method IN ('CASH', 'ONLINE')),
    online_order_paid numeric(12,2) NOT NULL DEFAULT 0 CHECK (online_order_paid >= 0),
    online_tip numeric(12,2) NOT NULL DEFAULT 0 CHECK (online_tip >= 0),
    cash_tip numeric(12,2) NOT NULL DEFAULT 0 CHECK (cash_tip >= 0),
    provider_reference text,
    verified_at timestamptz,
    CHECK ((method = 'CASH' AND online_order_paid = 0 AND online_tip = 0)
        OR (method = 'ONLINE' AND cash_tip = 0 AND verified_at IS NOT NULL))
);

CREATE TABLE public.driver_settlement (
    settlement_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shift_id bigint NOT NULL UNIQUE REFERENCES public.driver_shift(shift_id),
    driver_id bigint NOT NULL REFERENCES public.driver_profile(driver_id),
    branch_id integer NOT NULL REFERENCES public.branch(branch_id),
    manager_id bigint REFERENCES public.customers(id),
    manager_username varchar(255) NOT NULL,
    order_sales numeric(12,2) NOT NULL,
    online_order_paid numeric(12,2) NOT NULL DEFAULT 0,
    online_tips numeric(12,2) NOT NULL DEFAULT 0,
    cash_tips numeric(12,2) NOT NULL DEFAULT 0,
    hourly_pay numeric(12,2) NOT NULL,
    delivery_pay numeric(12,2) NOT NULL,
    expected_cash_due numeric(12,2) NOT NULL,
    cash_handed_in numeric(12,2) NOT NULL DEFAULT 0 CHECK (cash_handed_in >= 0),
    cash_paid_out numeric(12,2) NOT NULL DEFAULT 0 CHECK (cash_paid_out >= 0),
    variance numeric(12,2) NOT NULL,
    variance_reason text,
    settled_at timestamptz NOT NULL DEFAULT now()
);

DO $$
DECLARE runtime_role text := current_setting('app.runtime_role'); table_name text;
BEGIN
    FOREACH table_name IN ARRAY ARRAY['driver_profile', 'driver_shift', 'delivery_assignment',
            'driver_dispatch_event', 'driver_settlement', 'delivery_payment'] LOOP
        EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', table_name);
        EXECUTE format('ALTER TABLE public.%I FORCE ROW LEVEL SECURITY', table_name);
        EXECUTE format('CREATE POLICY owner_maintenance ON public.%I TO %I USING (true) WITH CHECK (true)', table_name, current_user);
        IF table_name = 'delivery_payment' THEN
            EXECUTE format('GRANT SELECT ON public.%I TO %I', table_name, runtime_role);
        ELSIF table_name IN ('driver_dispatch_event', 'driver_settlement') THEN
            EXECUTE format('GRANT SELECT, INSERT ON public.%I TO %I', table_name, runtime_role);
        ELSE
            EXECUTE format('GRANT SELECT, INSERT, UPDATE ON public.%I TO %I', table_name, runtime_role);
        END IF;
    END LOOP;
    FOREACH table_name IN ARRAY ARRAY['driver_shift', 'delivery_assignment', 'driver_dispatch_event', 'driver_settlement'] LOOP
        EXECUTE format('GRANT USAGE, SELECT ON SEQUENCE %s TO %I', pg_get_serial_sequence('public.' || table_name,
            CASE table_name WHEN 'driver_shift' THEN 'shift_id' WHEN 'delivery_assignment' THEN 'assignment_id'
            WHEN 'driver_dispatch_event' THEN 'event_id' ELSE 'settlement_id' END), runtime_role);
    END LOOP;
END $$;

