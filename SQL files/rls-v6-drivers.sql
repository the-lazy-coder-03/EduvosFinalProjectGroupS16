CREATE FUNCTION app_security.promote_branch_driver(email_value text, branch_value integer) RETURNS bigint
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, pg_temp AS $$
DECLARE target_id bigint; current_level smallint;
BEGIN
    IF app_security.actor_role() NOT IN ('ADMIN', 'SUPER_ADMIN')
       OR (app_security.actor_role() = 'ADMIN' AND app_security.actor_branch_id() <> branch_value)
       OR NOT EXISTS (SELECT 1 FROM public.branch WHERE branch_id = branch_value AND active) THEN
        RAISE EXCEPTION 'Driver promotion is not permitted' USING ERRCODE = '42501';
    END IF;
    SELECT id, access_level INTO target_id, current_level FROM public.customers
    WHERE lower(email) = lower(btrim(email_value)) AND NOT environment_admin FOR UPDATE;
    IF target_id IS NULL OR current_level <> 0 THEN
        RAISE EXCEPTION 'Registered customer account is required' USING ERRCODE = '22023';
    END IF;
    UPDATE public.customers SET role = 'DRIVER', access_level = 4 WHERE id = target_id;
    INSERT INTO public.driver_profile(driver_id, branch_id) VALUES(target_id, branch_value);
    RETURN target_id;
END $$;
REVOKE ALL ON FUNCTION app_security.promote_branch_driver(text, integer) FROM PUBLIC;

CREATE FUNCTION app_security.guard_driver_profile() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog, pg_temp AS $$
BEGIN
    IF NEW.driver_id IS DISTINCT FROM OLD.driver_id OR NEW.branch_id IS DISTINCT FROM OLD.branch_id
       OR NEW.created_at IS DISTINCT FROM OLD.created_at THEN
        RAISE EXCEPTION 'Driver identity and branch cannot be changed' USING ERRCODE = '42501';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER guard_driver_profile BEFORE UPDATE ON public.driver_profile
    FOR EACH ROW EXECUTE FUNCTION app_security.guard_driver_profile();
REVOKE ALL ON FUNCTION app_security.guard_driver_profile() FROM PUBLIC;

CREATE FUNCTION app_security.guard_driver_shift() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog, pg_temp AS $$
DECLARE profile_branch integer; profile_hourly numeric(10,2); profile_delivery numeric(10,2); profile_active boolean;
BEGIN
    IF TG_OP = 'INSERT' THEN
        SELECT branch_id, hourly_rate, per_delivery_rate, active
        INTO profile_branch, profile_hourly, profile_delivery, profile_active
        FROM public.driver_profile WHERE driver_id = NEW.driver_id;
        IF NOT profile_active OR NEW.branch_id IS DISTINCT FROM profile_branch
           OR NEW.hourly_rate IS DISTINCT FROM profile_hourly
           OR NEW.per_delivery_rate IS DISTINCT FROM profile_delivery
           OR NEW.business_date IS DISTINCT FROM (now() AT TIME ZONE 'Africa/Johannesburg')::date
           OR NEW.state <> 'ACTIVE' OR NEW.clocked_out_at IS NOT NULL
           OR NEW.approved_minutes IS NOT NULL OR NEW.returning_at IS NOT NULL
           OR NEW.clocked_in_at > now() OR NEW.clocked_in_at < now() - interval '1 minute' THEN
            RAISE EXCEPTION 'Invalid driver shift clock-in' USING ERRCODE = '23514';
        END IF;
        RETURN NEW;
    END IF;
    IF NEW.shift_id IS DISTINCT FROM OLD.shift_id OR NEW.driver_id IS DISTINCT FROM OLD.driver_id
       OR NEW.branch_id IS DISTINCT FROM OLD.branch_id OR NEW.business_date IS DISTINCT FROM OLD.business_date
       OR NEW.clocked_in_at IS DISTINCT FROM OLD.clocked_in_at
       OR NEW.hourly_rate IS DISTINCT FROM OLD.hourly_rate
       OR NEW.per_delivery_rate IS DISTINCT FROM OLD.per_delivery_rate
       OR OLD.state = 'SETTLED' THEN
        RAISE EXCEPTION 'Shift history cannot be changed' USING ERRCODE = '42501';
    END IF;
    IF app_security.actor_role() = 'DRIVER' THEN
        IF NEW.approved_minutes IS DISTINCT FROM OLD.approved_minutes OR NEW.state = 'SETTLED'
           OR (OLD.state = 'CLOCKED_OUT' AND NEW.state <> OLD.state)
           OR (OLD.state = 'ACTIVE' AND NEW.state NOT IN ('ACTIVE', 'CLOCKED_OUT'))
           OR (NEW.state = 'ACTIVE' AND NEW.clocked_out_at IS NOT NULL)
           OR (NEW.state = 'CLOCKED_OUT' AND (OLD.state <> 'ACTIVE' OR NEW.clocked_out_at IS NULL))
           OR (NEW.clocked_out_at IS DISTINCT FROM OLD.clocked_out_at
               AND (OLD.clocked_out_at IS NOT NULL OR NEW.clocked_out_at > now()
                    OR NEW.clocked_out_at < now() - interval '1 minute'))
           OR (NEW.returning_at IS DISTINCT FROM OLD.returning_at AND NEW.returning_at IS NOT NULL
               AND (NEW.returning_at > now() OR NEW.returning_at < now() - interval '1 minute')) THEN
            RAISE EXCEPTION 'Invalid driver shift transition' USING ERRCODE = '42501';
        END IF;
    END IF;
    IF NEW.state = 'SETTLED' AND (OLD.state <> 'CLOCKED_OUT'
       OR NEW.approved_minutes IS NULL OR NOT EXISTS (
           SELECT 1 FROM public.driver_settlement WHERE shift_id = NEW.shift_id)) THEN
        RAISE EXCEPTION 'Shift requires a completed settlement' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER guard_driver_shift BEFORE INSERT OR UPDATE ON public.driver_shift
    FOR EACH ROW EXECUTE FUNCTION app_security.guard_driver_shift();
REVOKE ALL ON FUNCTION app_security.guard_driver_shift() FROM PUBLIC;

CREATE FUNCTION app_security.guard_delivery_assignment() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog, pg_temp AS $$
DECLARE order_branch integer; order_type_value text; kitchen_status text;
    shift_driver bigint; shift_branch integer; shift_state text;
BEGIN
    SELECT branch_id, order_type, status INTO order_branch, order_type_value, kitchen_status
    FROM public.customer_order WHERE order_id = NEW.order_id;
    SELECT driver_id, branch_id, state INTO shift_driver, shift_branch, shift_state
    FROM public.driver_shift WHERE shift_id = NEW.shift_id;
    IF order_type_value IS DISTINCT FROM 'delivery' OR NEW.branch_id IS DISTINCT FROM order_branch
       OR NEW.driver_id IS DISTINCT FROM shift_driver OR NEW.branch_id IS DISTINCT FROM shift_branch
       OR shift_state <> 'ACTIVE' THEN
        RAISE EXCEPTION 'Assignment must match a delivery order and driver shift' USING ERRCODE = '23514';
    END IF;
    IF TG_OP = 'INSERT' AND (NEW.state <> 'ASSIGNED' OR NEW.picked_up_at IS NOT NULL
       OR NEW.delivered_at IS NOT NULL OR kitchen_status NOT IN ('Pending', 'Preparing', 'Completed')) THEN
        RAISE EXCEPTION 'Invalid new assignment' USING ERRCODE = '23514';
    END IF;
    IF TG_OP = 'UPDATE' THEN
        IF NEW.order_id IS DISTINCT FROM OLD.order_id OR NEW.branch_id IS DISTINCT FROM OLD.branch_id
           OR OLD.state IN ('DELIVERED', 'CANCELLED') OR NEW.assigned_at IS DISTINCT FROM OLD.assigned_at THEN
            RAISE EXCEPTION 'Assignment history cannot be changed' USING ERRCODE = '42501';
        END IF;
        IF (NEW.driver_id IS DISTINCT FROM OLD.driver_id OR NEW.shift_id IS DISTINCT FROM OLD.shift_id)
           AND (OLD.state <> 'ASSIGNED' OR app_security.actor_role() NOT IN ('ADMIN', 'SUPER_ADMIN')) THEN
            RAISE EXCEPTION 'Only a manager can reassign before pickup' USING ERRCODE = '42501';
        END IF;
        IF app_security.actor_role() = 'DRIVER' AND
           (NEW.driver_id IS DISTINCT FROM OLD.driver_id OR NEW.shift_id IS DISTINCT FROM OLD.shift_id
           OR NEW.self_claimed IS DISTINCT FROM OLD.self_claimed OR NEW.assigned_by IS DISTINCT FROM OLD.assigned_by
           OR (OLD.state = 'ASSIGNED' AND NEW.state NOT IN ('ASSIGNED', 'PICKED_UP'))
           OR (OLD.state = 'PICKED_UP' AND NEW.state NOT IN ('PICKED_UP', 'DELIVERED'))) THEN
            RAISE EXCEPTION 'Invalid driver assignment transition' USING ERRCODE = '42501';
        END IF;
        IF (OLD.state = 'ASSIGNED' AND NEW.state = 'PICKED_UP'
                AND (kitchen_status <> 'Completed' OR NEW.picked_up_at IS NULL
                    OR NEW.picked_up_at > now() OR NEW.picked_up_at < now() - interval '1 minute'))
           OR (OLD.state = 'PICKED_UP' AND NEW.state = 'DELIVERED'
                AND (NEW.delivered_at IS NULL OR NEW.delivered_at > now()
                    OR NEW.delivered_at < now() - interval '1 minute'))
           OR (NEW.state <> OLD.state AND NOT (
                OLD.state = 'ASSIGNED' AND NEW.state IN ('PICKED_UP', 'CANCELLED')
                OR OLD.state = 'PICKED_UP' AND NEW.state = 'DELIVERED'))
           OR (NEW.picked_up_at IS DISTINCT FROM OLD.picked_up_at AND NEW.state <> 'PICKED_UP')
           OR (NEW.delivered_at IS DISTINCT FROM OLD.delivered_at AND NEW.state <> 'DELIVERED') THEN
            RAISE EXCEPTION 'Invalid delivery transition' USING ERRCODE = '23514';
        END IF;
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER guard_delivery_assignment BEFORE INSERT OR UPDATE ON public.delivery_assignment
    FOR EACH ROW EXECUTE FUNCTION app_security.guard_delivery_assignment();
REVOKE ALL ON FUNCTION app_security.guard_delivery_assignment() FROM PUBLIC;

CREATE FUNCTION app_security.claim_next_delivery(shift_value bigint) RETURNS bigint
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, pg_temp AS $$
DECLARE driver_value bigint; branch_value integer; order_value bigint;
BEGIN
    driver_value := app_security.actor_customer_id();
    IF app_security.actor_role() <> 'DRIVER' THEN
        RAISE EXCEPTION 'Driver access is required' USING ERRCODE = '42501';
    END IF;
    SELECT s.branch_id INTO branch_value FROM public.driver_shift s JOIN public.driver_profile p ON p.driver_id = s.driver_id
    WHERE s.shift_id = shift_value AND s.driver_id = driver_value AND s.state = 'ACTIVE' AND p.active
      AND p.branch_id = s.branch_id FOR UPDATE OF s;
    IF branch_value IS NULL THEN
        RAISE EXCEPTION 'Active shift is required' USING ERRCODE = '22023';
    END IF;
    IF EXISTS (SELECT 1 FROM public.delivery_assignment a WHERE a.driver_id = driver_value
            AND a.self_claimed AND a.state IN ('ASSIGNED', 'PICKED_UP')) THEN
        RAISE EXCEPTION 'Finish the claimed delivery first' USING ERRCODE = '22023';
    END IF;
    SELECT o.order_id INTO order_value FROM public.customer_order o
    WHERE o.branch_id = branch_value AND o.order_type = 'delivery'
      AND o.status IN ('Pending', 'Preparing', 'Completed')
      AND NOT EXISTS (SELECT 1 FROM public.delivery_assignment a WHERE a.order_id = o.order_id)
    ORDER BY o.created_at, o.order_id LIMIT 1 FOR UPDATE OF o SKIP LOCKED;
    IF order_value IS NULL THEN RETURN NULL; END IF;
    INSERT INTO public.delivery_assignment(order_id, driver_id, shift_id, branch_id, self_claimed)
    VALUES (order_value, driver_value, shift_value, branch_value, true);
    RETURN order_value;
END $$;
